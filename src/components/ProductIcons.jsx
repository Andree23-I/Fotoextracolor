// ============================================================================
// Article Mockup Visual / Icon Resolver
// If the product has a photo (imageUrl/image), render the image photo!
// If no photo exists, render clean SVG vector icon from 21st.dev/Lucide
// ============================================================================
export function ArticleMockupIcon({
  product,
  mockupType,
  category,
  size = 28,
  className = "",
  style = {}
}) {
  const photo = product?.imageUrl || product?.image;

  if (photo) {
    return (
      <img
        src={photo}
        alt={product?.titleIt || "Articolo"}
        className={`article-custom-img ${className}`}
        style={{
          width: size,
          height: size,
          objectFit: "cover",
          borderRadius: 6,
          ...style
        }}
      />
    );
  }

  const type = mockupType || product?.mockupType;
  const cat = category || product?.category;
  const pid = product?.id || "";

  if (type === "mug" || pid.includes("mug")) {
    return <SvgMug size={size} className={className} style={style} />;
  }
  if (type === "cushion" || pid.includes("pillow") || pid.includes("cuscino")) {
    return <SvgCushion size={size} className={className} style={style} />;
  }
  if (type === "puzzle" || pid.includes("puzzle")) {
    return <SvgPuzzle size={size} className={className} style={style} />;
  }
  if (type === "tshirt" || pid.includes("tshirt") || pid.includes("maglia")) {
    return <SvgTshirt size={size} className={className} style={style} />;
  }
  if (type === "keychain" || pid.includes("keychain") || pid.includes("portachiavi")) {
    return <SvgKeychain size={size} className={className} style={style} />;
  }
  if (type === "canvas" || pid.includes("canvas") || cat === "wallart") {
    return <SvgCanvas size={size} className={className} style={style} />;
  }
  if (cat === "photobooks" || pid.includes("book")) {
    return <SvgBook size={size} className={className} style={style} />;
  }
  if (pid.includes("film") || pid.includes("scan")) {
    return <SvgFilm size={size} className={className} style={style} />;
  }
  if (pid.includes("vhs") || pid.includes("tape")) {
    return <SvgTape size={size} className={className} style={style} />;
  }
  if (type === "print" || cat === "prints" || pid.includes("print") || pid.includes("poster")) {
    return <SvgPrint size={size} className={className} style={style} />;
  }

  return <SvgBox size={size} className={className} style={style} />;
}
